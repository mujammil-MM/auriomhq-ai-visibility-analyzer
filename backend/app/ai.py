"""Optional AI recommendation layer (provider-replaceable).

Design rules
------------
* The analysis engine is fully functional **without** an API key. When AI is
  disabled or fails, the rule-based summary and recommendations are used and
  the audit is marked ``aiEnhanced: false``.
* The model only receives an evidence pack produced by the crawler plus the
  findings already computed locally. The prompt forbids inventing findings,
  metrics, quotes or citations.
* Only server-side configuration is used: the key never reaches the browser.
* Any provider exposing an OpenAI-compatible ``/chat/completions`` endpoint
  works — change ``AI_BASE_URL`` and ``AI_MODEL`` (OpenAI, Azure OpenAI,
  OpenRouter, Groq, Together, self-hosted vLLM, …).
"""
from __future__ import annotations

import json
import logging
from typing import Any

import httpx

from .analyzers.base import CheckResult
from .analyzers.scoring import ScoreSummary
from .config import settings

logger = logging.getLogger("auriomhq.ai")

SYSTEM_PROMPT = """You are a senior technical SEO / AEO / GEO consultant at AuriomHQ.
You will receive a JSON evidence pack generated by an automated crawler plus the
rule-based findings for one website.

Hard rules:
1. Use ONLY the supplied evidence. Never invent findings, metrics, page copy,
   search rankings, traffic figures, citations or competitor data.
2. Do not promise ranking improvements or guaranteed AI citations.
3. If the evidence does not support a claim, omit the claim.
4. Be concrete and specific to this website (reference its actual page titles,
   headings, schema types or missing elements).
5. Plain business English. No hype, no emoji, no marketing superlatives.

Return ONLY valid JSON matching this shape:
{
  "executiveSummary": "2-3 sentences",
  "keyFindings": [{"title": "...", "detail": "..."}],   // 3-5 items
  "priorityActions": [{"title": "...", "detail": "...", "effort": "Easy|Moderate|Hard"}]  // 3-5 items, ordered
}"""


def rule_based_summary(crawl: Any, results: list[CheckResult], scores: ScoreSummary) -> dict[str, Any]:
    """Deterministic executive summary used when AI is disabled."""
    counts = {
        "fail": sum(1 for r in results if r.status == "fail"),
        "warning": sum(1 for r in results if r.status == "warning"),
        "pass": sum(1 for r in results if r.status == "pass"),
        "not_tested": sum(1 for r in results if r.status == "not_tested"),
    }
    critical = [r for r in results if r.status == "fail" and r.severity == "critical"]
    weakest = min(
        (p for p in scores.pillars.values() if p.score is not None),
        key=lambda p: p.score, default=None,
    )
    strongest = max(
        (p for p in scores.pillars.values() if p.score is not None),
        key=lambda p: p.score, default=None,
    )
    headline = (
        f"{crawl.final_url} scores {scores.overall}/100 for AI visibility"
        if scores.overall is not None else f"{crawl.final_url} could not be fully scored"
    )
    parts = [
        f"{headline} (SEO {scores.pillars['seo'].score if scores.pillars['seo'].score is not None else '—'}, "
        f"AEO {scores.pillars['aeo'].score if scores.pillars['aeo'].score is not None else '—'}, "
        f"GEO {scores.pillars['geo'].score if scores.pillars['geo'].score is not None else '—'}), "
        f"based on {len(crawl.pages)} crawled page(s)."
    ]
    parts.append(
        f"We measured {counts['pass'] + counts['fail'] + counts['warning']} checks: "
        f"{counts['pass']} passed, {counts['warning']} warned and {counts['fail']} failed."
        + (f" {counts['not_tested']} could not be tested." if counts["not_tested"] else "")
    )
    if critical:
        parts.append(
            "The most urgent problems are: "
            + "; ".join(f"{r.title.lower()} ({r.evidence[:120]})" for r in critical[:3]) + "."
        )
    if weakest and strongest and weakest.pillar != strongest.pillar:
        parts.append(
            f"{weakest.label} is the weakest pillar ({weakest.score}/100) while {strongest.label} is the strongest "
            f"({strongest.score}/100). Focusing first on {weakest.label} gives the largest uplift for the same effort."
        )

    findings = []
    for r in critical[:3]:
        findings.append({"title": r.title, "detail": r.evidence})
    for r in [x for x in results if x.status == "warning"][:2]:
        findings.append({"title": r.title, "detail": r.evidence})

    actions = []
    for r in [x for x in results if x.status in {"fail", "warning"} and x.severity in {"critical", "high"}][:4]:
        actions.append({"title": r.title, "detail": r.fix, "effort": "Moderate"})

    return {
        "executiveSummary": " ".join(parts),
        "keyFindings": findings[:5],
        "priorityActions": actions[:5],
        "aiEnhanced": False,
        "source": "rule_based",
    }


async def enhance_with_ai(crawl: Any, results: list[CheckResult], scores: ScoreSummary,
                          evidence: dict[str, Any]) -> dict[str, Any] | None:
    """Call the configured LLM provider. Returns None when unavailable/invalid."""
    if not settings.ai_ready:
        return None
    payload = {
        "model": settings.ai_model,
        "temperature": 0.2,
        "max_tokens": 900,
        "response_format": {"type": "json_object"},
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": json.dumps(evidence, ensure_ascii=False)[:16000]},
        ],
    }
    url = settings.ai_base_url.rstrip("/") + "/chat/completions"
    headers = {"Authorization": f"Bearer {settings.ai_api_key}", "Content-Type": "application/json"}
    try:
        async with httpx.AsyncClient(timeout=settings.ai_timeout, trust_env=False) as client:
            response = await client.post(url, headers=headers, json=payload)
            if response.status_code >= 400:
                logger.warning("AI provider returned %s", response.status_code)
                return None
            data = response.json()
            content = data["choices"][0]["message"]["content"]
            parsed = json.loads(content)
    except Exception as exc:  # network, quota, malformed JSON — degrade gracefully
        logger.warning("AI enhancement skipped: %s", type(exc).__name__)
        return None

    summary = str(parsed.get("executiveSummary", "")).strip()
    if len(summary) < 40:
        return None
    findings = [
        {"title": str(f.get("title", ""))[:160], "detail": str(f.get("detail", ""))[:600]}
        for f in parsed.get("keyFindings", []) if isinstance(f, dict)
    ][:5]
    actions = [
        {
            "title": str(a.get("title", ""))[:160],
            "detail": str(a.get("detail", ""))[:700],
            "effort": str(a.get("effort", "Moderate"))[:12],
        }
        for a in parsed.get("priorityActions", []) if isinstance(a, dict)
    ][:5]
    return {
        "executiveSummary": summary[:1200],
        "keyFindings": [f for f in findings if f["title"]],
        "priorityActions": [a for a in actions if a["title"]],
        "aiEnhanced": True,
        "source": f"{settings.ai_provider}:{settings.ai_model}",
        "disclaimer": "AI wording is generated from crawl evidence only and reviewed as advisory copy.",
    }
