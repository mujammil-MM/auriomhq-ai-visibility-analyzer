import { AlertTriangle, Download, Loader2 } from 'lucide-react';
import { useEffect, useState } from 'react';
import { Link, useParams } from 'react-router-dom';
import { Dashboard } from '../components/Dashboard';
import { api, ApiError } from '../lib/api';
import type { Report } from '../lib/types';

export function SharedReportPage() {
  const { token = '' } = useParams();
  const [report, setReport] = useState<Report | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    let cancelled = false;
    api
      .getSharedReport(token)
      .then((data) => {
        if (!cancelled) setReport(data);
      })
      .catch((err) => {
        if (cancelled) return;
        setError(
          err instanceof ApiError && err.status === 404
            ? 'This report link is not valid, or the owner has made it private.'
            : 'Could not load this report.',
        );
      })
      .finally(() => {
        if (!cancelled) setLoading(false);
      });
    return () => {
      cancelled = true;
    };
  }, [token]);

  if (loading) {
    return (
      <div className="flex min-h-[50vh] items-center justify-center">
        <Loader2 className="h-5 w-5 animate-spin text-faint" />
      </div>
    );
  }

  if (error || !report) {
    return (
      <div className="mx-auto max-w-lg px-5 py-24 text-center sm:px-8">
        <span className="inline-flex h-10 w-10 items-center justify-center rounded-full bg-warnSoft text-warn">
          <AlertTriangle className="h-5 w-5" />
        </span>
        <h1 className="mt-4 text-xl font-semibold tracking-[-0.02em]">Report unavailable</h1>
        <p className="mt-2 text-sm leading-relaxed text-muted">{error}</p>
        <div className="mt-6 flex justify-center gap-2">
          <Link to="/" className="btn-primary">
            Analyse a website
          </Link>
          <a href="https://auriomhq.work/contact" target="_blank" rel="noreferrer" className="btn-secondary">
            Contact AuriomHQ
          </a>
        </div>
      </div>
    );
  }

  return (
    <>
      <div className="border-b border-line bg-[#F6F4EE]">
        <div className="mx-auto flex w-full max-w-[1180px] flex-wrap items-center justify-between gap-3 px-5 py-3 sm:px-8">
          <p className="text-xs text-muted">
            Read-only shared audit · generated by the AuriomHQ AI Visibility Analyzer
          </p>
          <a href={api.sharedPdfUrl(token)} className="btn-secondary h-8 px-3 text-[11px]">
            <Download className="h-3 w-3" /> Download PDF
          </a>
        </div>
      </div>
      <Dashboard report={report} sharedView />
    </>
  );
}
